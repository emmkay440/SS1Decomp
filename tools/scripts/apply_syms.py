#!/usr/bin/env python3
"""Replace raw RAM/IO addresses in asm/ with names from config/ram_symbols.txt
and config/io_regs.txt, and regenerate ld_symbols.ld. Safe to re-run.

config/rom_symbols.txt (ROM data tables and link-time constants) only goes
into ld_symbols.ld; asm/ keeps raw ROM addresses.

Only literal pool words (.4byte) and their "@ =" load comments are rewritten,
and only when the value exactly equals a named address.
"""
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)

def load(path):
    t = {}
    for line in open(path):
        f = line.split("#")[0].split()
        if len(f) >= 2:
            t[int(f[0], 16)] = f[1]
    return t

syms = {**load("config/io_regs.txt"), **load("config/ram_symbols.txt")}
rom_syms = load("config/rom_symbols.txt")
by_name = {v: k for k, v in {**syms, **rom_syms}.items()}

pat = re.compile(r"(?<=\.4byte )0x(0[234][0-9A-F]{6})\b|(?<=@ =)0x(0[234][0-9A-F]{6})\b")
def sub(m):
    v = int(m.group(1) or m.group(2), 16)
    return syms.get(v, m.group(0))

changed = 0
for p in glob.glob("asm/*.s") + glob.glob("asm/lib/*.s"):
    s = open(p).read()
    t = pat.sub(sub, s)
    if t != s:
        open(p, "w").write(t)
        changed += 1

with open("ld_symbols.ld", "w") as f:
    f.write("/* Generated by tools/scripts/apply_syms.py - edit config/*.txt instead */\n")
    for name, a in sorted(by_name.items(), key=lambda x: x[1]):
        f.write(f"{name} = 0x{a:08X};\n")
print(f"updated {changed} files, {len(by_name)} symbols")
